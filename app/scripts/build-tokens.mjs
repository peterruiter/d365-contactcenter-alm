// Generates src/ui/capgemini/tokens.css from the vendored Capgemini Zodiak tokens.json.
// No dependencies. Run with `npm run tokens` from app/.
//
// Output:
//   :root, [data-theme="light"]  every colour token (light value), plus spacing, radius,
//                                 shadow and font-family tokens
//   [data-theme="dark"]           every colour token (dark value)
//   .t-<style>                    one class per type style, with the documented step-down
//                                 for h1/h2/h3 below 768px
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const srcFile = resolve(here, '../src/ui/capgemini/tokens.json')
const outFile = resolve(here, '../src/ui/capgemini/tokens.css')

const tokens = JSON.parse(readFileSync(srcFile, 'utf8'))
const THEMES = ['light', 'dark']
const BREAKPOINT = 768

// ------------------------------------------------------------------ colour

const colorList = tokens.color.tokens
const byName = new Map(colorList.map((t) => [t.name, t]))

/** Value of a token for a theme, before alias resolution. A plain value is the same in both. */
function rawValue(token, theme) {
  const v = token.value
  if (v && typeof v === 'object') return v[theme] ?? v.light
  return v
}

/** Resolves "{other-token}" aliases recursively for one theme. */
function resolveColor(name, theme, seen = []) {
  if (seen.includes(name)) throw new Error(`Alias cycle: ${[...seen, name].join(' -> ')}`)
  const token = byName.get(name)
  if (!token) throw new Error(`Unknown colour token "${name}" (referenced from ${seen.at(-1) ?? 'root'})`)
  const v = String(rawValue(token, theme)).trim()
  const alias = /^\{([^}]+)\}$/.exec(v)
  return alias ? resolveColor(alias[1], theme, [...seen, name]) : v
}

const colors = Object.fromEntries(
  THEMES.map((theme) => [theme, colorList.map((t) => [t.name, resolveColor(t.name, theme)])]),
)

// --------------------------------------------------------- other families

const scalar = (family) => (tokens[family]?.tokens ?? []).map((t) => [t.name, String(t.value)])
const spacing = scalar('spacing')
const radius = scalar('radius')
const shadow = scalar('shadow')
const families = tokens.type?.families ?? {}

// -------------------------------------------------------------- type styles

const px = (v) => (typeof v === 'number' ? `${v}px` : String(v))
const styles = []
for (const group of tokens.type?.groups ?? []) {
  for (const s of group.styles) styles.push({ ...s, family: s.family ?? group.family })
}

/** "Steps down to 32px below 768px." in the usage text gives the small-screen size. */
const stepDown = new Map()
for (const s of styles) {
  const m = /Steps down to (\d+(?:\.\d+)?px) below (\d+)px/i.exec(s.usage ?? '')
  if (m) stepDown.set(s.name, m[1])
}
// h1-light is documented as h1 set for heavy grounds, with the same metrics; give it h1's step.
if (stepDown.has('h1') && !stepDown.has('h1-light')) stepDown.set('h1-light', stepDown.get('h1'))

function typeRule(s) {
  const decl = [`font-family: var(--font-${s.family ?? 'sans'});`, `font-size: ${px(s.fontSize)};`]
  if (s.lineHeight !== undefined) decl.push(`line-height: ${s.lineHeight};`)
  if (s.fontWeight !== undefined) decl.push(`font-weight: ${s.fontWeight};`)
  if (s.fontStyle) decl.push(`font-style: ${s.fontStyle};`)
  if (s.letterSpacing !== undefined) decl.push(`letter-spacing: ${s.letterSpacing};`)
  return `.t-${s.name} {\n  ${decl.join('\n  ')}\n}`
}

// ------------------------------------------------------------------- write

const vars = (pairs) => pairs.map(([n, v]) => `  --${n}: ${v};`).join('\n')

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit by hand.
   Capgemini Zodiak tokens. Paint with the semantic tokens (page-background, surface-*, text-*,
   border-*, action-*, negative-*); brand-* and the ramps are reference values. */

:root,
[data-theme="light"] {
  color-scheme: light;
${vars(colors.light)}
}

[data-theme="dark"] {
  color-scheme: dark;
${vars(colors.dark)}
}

:root {
  /* Spacing */
${vars(spacing)}

  /* Radius */
${vars(radius)}

  /* Shadow */
${vars(shadow)}

  /* Font families */
${vars(Object.entries(families).map(([k, v]) => [`font-${k}`, v]))}
}

/* Type styles */
${styles.map(typeRule).join('\n\n')}

@media (max-width: ${BREAKPOINT - 0.02}px) {
${[...stepDown.entries()].map(([n, size]) => `  .t-${n} { font-size: ${size}; }`).join('\n')}
}
`

writeFileSync(outFile, css)
console.log(
  `tokens.css: ${colorList.length} colours x ${THEMES.length} themes, ${spacing.length} spacing, ` +
    `${radius.length} radius, ${shadow.length} shadow, ${styles.length} type styles -> ${outFile}`,
)
